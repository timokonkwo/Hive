#!/usr/bin/env node

import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { createJiti } from "jiti";
import { createPublicClient, createWalletClient, http } from "viem";
import { privateKeyToAccount } from "viem/accounts";

function loadEnvFile(path) {
  if (!existsSync(path)) return;
  const content = readFileSync(path, "utf8");
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const match = trimmed.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (!match) continue;
    const [, key, rawValue] = match;
    if (process.env[key]) continue;
    let value = rawValue.trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    process.env[key] = value;
  }
}

function assertReady(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

const root = resolve(new URL("..", import.meta.url).pathname);
loadEnvFile(resolve(root, ".env"));
loadEnvFile(resolve(root, ".env.local"));

process.env.BNB_ALLOW_PROCESS_STORAGE = "true";
delete process.env.MONGODB_URI;

const jiti = createJiti(import.meta.url, {
  alias: {
    "@": root,
  },
});

const { bscTestnet } = await import("viem/chains");
const { buildBnbJobSpec } = await jiti.import("../lib/bnb/jobs.ts");
const {
  createBnbActivationRecord,
  confirmBnbActivationPayment,
  updateBnbActivationRecord,
} = await jiti.import("../lib/bnb/records.ts");
const {
  buildBnbEscrowPaymentRequest,
  buildBnbEscrowSettlementRequest,
  readBnbEscrowSettlement,
} = await jiti.import("../lib/bnb/escrow.ts");
const { runBnbAgentWork } = await jiti.import("../lib/bnb/agent-runner.ts");
const { getBscChainId, getBscNativeSymbol, getBscRpcUrl } = await jiti.import("../lib/bnb/chain.ts");

const chainId = getBscChainId();
assertReady(chainId === 97, `Refusing to run smoke test on chain ${chainId}. Set BNB_NETWORK=testnet and BNB_BSC_CHAIN_ID=97.`);

const rawPrivateKey = process.env.BNB_DEPLOYER_PRIVATE_KEY?.trim() || "";
const privateKey = rawPrivateKey.startsWith("0x") ? rawPrivateKey : `0x${rawPrivateKey}`;
assertReady(/^0x[0-9a-fA-F]{64}$/.test(privateKey), "BNB_DEPLOYER_PRIVATE_KEY is missing or invalid.");
assertReady(process.env.BNB_AGENT_ESCROW_ADDRESS?.trim(), "BNB_AGENT_ESCROW_ADDRESS is required.");

const account = privateKeyToAccount(privateKey);
const rpcUrl = getBscRpcUrl();
const nativeSymbol = getBscNativeSymbol();
const publicClient = createPublicClient({
  chain: bscTestnet,
  transport: http(rpcUrl),
});
const walletClient = createWalletClient({
  account,
  chain: bscTestnet,
  transport: http(rpcUrl),
});

const budgetAmount = process.env.BNB_SMOKE_BUDGET?.trim() || "0.0001";
const agent = {
  chainId,
  tokenId: `hive-smoke-${Date.now()}`,
  name: "Hive Testnet Health Agent",
  description: "BSC Testnet lifecycle smoke agent.",
  category: "Health Factor Monitoring",
  ownerAddress: account.address,
  agentWallet: account.address,
  identityRegistry: "testnet-smoke",
  services: [],
  capabilities: ["wallet-check", "health-factor"],
  x402Support: false,
  erc8183Support: false,
  mcpSupport: false,
  a2aSupport: false,
  feedback: {
    count: 1,
    positive: 1,
    score: 100,
    summary: "Local smoke lifecycle agent.",
  },
  lastActivity: new Date().toISOString(),
  activationStatus: "callable",
  executionStatus: "ready_to_run",
  executionEndpoints: [],
  sourceFreshness: {
    source: "local",
    fetchedAt: new Date().toISOString(),
    stale: false,
    note: "Generated by BSC Testnet smoke test.",
  },
};

const normalizedJob = buildBnbJobSpec({
  capability: "health_factor",
  taskType: "Check liquidation risk",
  fields: {
    walletOrPosition: account.address,
    protocol: "Venus",
    threshold: "1.6",
    requestedAction: "Report only",
  },
  instructions: "Smoke test lifecycle only. Do not execute a trading transaction.",
});

assertReady(normalizedJob.ok, normalizedJob.error || "Job spec failed validation.");

const record = await createBnbActivationRecord({
  agent,
  taskTemplate: normalizedJob.spec.summary,
  jobSpec: normalizedJob.spec,
  spendCap: `${budgetAmount} ${nativeSymbol}`,
  expiry: "1 hour",
  clientAddress: account.address,
});

const paymentRequest = buildBnbEscrowPaymentRequest(record);
assertReady(paymentRequest.status === "ready", paymentRequest.reason || "Escrow payment request was not ready.");

console.log(`Smoke account: ${account.address}`);
console.log(`Record: ${record.recordId}`);
console.log(`Funding escrow: ${paymentRequest.amountLabel}`);

const paymentHash = await walletClient.sendTransaction({
  account,
  chain: bscTestnet,
  to: paymentRequest.to,
  data: paymentRequest.data,
  value: BigInt(paymentRequest.value),
});

await publicClient.waitForTransactionReceipt({ hash: paymentHash, confirmations: 1 });
const funded = await confirmBnbActivationPayment({
  recordId: record.recordId,
  clientAddress: account.address,
  transactionHash: paymentHash,
});

assertReady(funded?.payment?.transactionStatus === "success", "Escrow funding was not confirmed.");
assertReady(funded.payment.jobId, "Escrow funding did not return a job ID.");
console.log(`Escrow funded: ${funded.payment.explorerUrl || paymentHash}`);

const startedAt = new Date().toISOString();
await updateBnbActivationRecord({
  recordId: funded.recordId,
  clientAddress: account.address,
  patch: {
    status: "running",
    work: { status: "running", startedAt },
    delivery: { status: "running", startedAt },
  },
});

const work = await runBnbAgentWork(funded);
assertReady(work.status === "completed", work.error || "Agent work did not complete.");
assertReady(work.output?.includes("Address checked:"), "Agent work output did not include the checked address.");

const delivered = await updateBnbActivationRecord({
  recordId: funded.recordId,
  clientAddress: account.address,
  patch: {
    status: "delivered",
    work,
    delivery: {
      status: "delivered",
      summary: work.output.split("\n").find(Boolean),
      rawOutput: work.output,
      dataSources: work.dataSources,
      startedAt: work.startedAt,
      completedAt: work.completedAt,
    },
  },
});

assertReady(delivered?.status === "delivered", "Delivered record was not saved.");
console.log(`Agent delivered: ${work.output.split("\n")[0]}`);

const settlementRequest = buildBnbEscrowSettlementRequest(delivered, "release");
assertReady(settlementRequest.status === "ready", settlementRequest.reason || "Settlement request was not ready.");

const releaseHash = await walletClient.sendTransaction({
  account,
  chain: bscTestnet,
  to: settlementRequest.to,
  data: settlementRequest.data,
  value: 0n,
});

await publicClient.waitForTransactionReceipt({ hash: releaseHash, confirmations: 1 });
const settlement = await readBnbEscrowSettlement(releaseHash, "release", settlementRequest.jobId);
assertReady(settlement.transactionStatus === "success", "Escrow release was not confirmed.");

const paid = await updateBnbActivationRecord({
  recordId: delivered.recordId,
  clientAddress: account.address,
  patch: {
    status: "paid",
    settlement: {
      action: "release",
      transactionHash: settlement.transactionHash,
      transactionStatus: settlement.transactionStatus,
      explorerUrl: settlement.explorerUrl,
      blockNumber: settlement.blockNumber,
    },
  },
});

assertReady(paid?.status === "paid", "Final paid record was not saved.");

const jobReadAbi = [
  {
    type: "function",
    name: "jobs",
    stateMutability: "view",
    inputs: [{ name: "jobId", type: "bytes32" }],
    outputs: [
      { name: "client", type: "address" },
      { name: "agent", type: "address" },
      { name: "amount", type: "uint256" },
      { name: "expiresAt", type: "uint64" },
      { name: "status", type: "uint8" },
      { name: "taskHash", type: "bytes32" },
      { name: "receiptId", type: "string" },
    ],
  },
];

const onchainJob = await publicClient.readContract({
  address: paymentRequest.contractAddress,
  abi: jobReadAbi,
  functionName: "jobs",
  args: [settlementRequest.jobId],
});
const onchainStatus = Array.isArray(onchainJob) ? Number(onchainJob[4]) : Number(onchainJob.status);
assertReady(onchainStatus === 2, `Expected onchain Released status 2, got ${onchainStatus}.`);

console.log(`Escrow released: ${settlement.explorerUrl || releaseHash}`);
console.log(`Final status: ${paid.status}`);
console.log("BNB Testnet lifecycle smoke passed.");
